"""Score agent-security extraction against hand-reviewed public ground truth.

    python -m benchmark.agent_security.evaluate [--cases FILE] [--checkouts DIR] [--out PREFIX]

Categories (each a set of tuples, compared exactly):

* ``agents``            ``file:symbol`` of every Agent construction
* ``delegations``       (parent source, child source, mechanism)
* ``mcp_server_tools``  (server file, tool function)
* ``mcp_connections``   (agent source, transport)
* ``server_links``      (agent source, repository server file)
* ``operations``        (``file:tool``, IAM action)

Only the static extraction is scored. Verdicts depend on identity manifests and
policies that public repositories do not ship, so they are not measurable here.
The scanned code is parsed, never imported or executed.
"""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path
from typing import Any

from aibom.agent_security.analyzer import analyze
from aibom.agent_security.models import AgentSecurityReport

HERE = Path(__file__).resolve().parent
CATEGORIES = (
    "agents",
    "delegations",
    "mcp_server_tools",
    "mcp_connections",
    "server_links",
    "operations",
)


def predicted(report: AgentSecurityReport) -> dict[str, set[tuple[str, ...]]]:
    source = {agent.id: agent.source for agent in report.agents}
    server_file = {server.id: server.file for server in report.mcp_servers}
    return {
        "agents": {(agent.source,) for agent in report.agents},
        "delegations": {
            (source.get(d.parent_id, d.parent_id), source.get(d.child_id or "", "?"), d.mechanism)
            for d in report.delegations
        },
        "mcp_server_tools": {
            (server.file, tool.name) for server in report.mcp_servers for tool in server.tools
        },
        "mcp_connections": {
            (source.get(c.client_ref, c.client_ref), c.transport)
            for c in report.mcp_connections
            if c.client_kind == "agent"
        },
        "server_links": {
            (source.get(c.client_ref, c.client_ref), server_file[c.server_id])
            for c in report.mcp_connections
            if c.client_kind == "agent" and c.server_id in server_file
        },
        "operations": {
            (f"{op.tool_file}:{op.tool_name}", op.action) for op in report.operations
        },
    }


def _included(item: tuple[str, ...], prefixes: list[str]) -> bool:
    return item[0].startswith(tuple(prefixes))


def score_case(case: dict[str, Any], checkouts: Path) -> dict[str, Any]:
    checkout = checkouts / case["checkout"]
    head = subprocess.run(
        ["git", "-C", str(checkout), "rev-parse", "HEAD"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    if head != case["commit"]:
        raise SystemExit(f"{case['id']}: checkout is at {head}, expected {case['commit']}")
    truth = json.loads((HERE / case["ground_truth"]).read_text(encoding="utf-8"))
    report = analyze(checkout / case["root"], auto_manifest=False)
    guess = predicted(report)
    result: dict[str, Any] = {"id": case["id"], "repository": case["repository"],
                              "commit": case["commit"], "root": case["root"], "categories": {}}
    for category in CATEGORIES:
        expected = {tuple(item) if isinstance(item, list) else (item,)
                    for item in truth.get(category, [])}
        found = {item for item in guess[category] if _included(item, case["include"])}
        result["categories"][category] = {
            "tp": len(expected & found),
            "fp": sorted("|".join(item) for item in found - expected),
            "fn": sorted("|".join(item) for item in expected - found),
        }
    result["unknown_reasons"] = sorted({u.reason for u in report.unknowns})
    return result


def _ratio(numerator: int, denominator: int) -> float | None:
    return round(numerator / denominator, 3) if denominator else None


def summarize(results: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    totals: dict[str, dict[str, Any]] = {}
    for category in CATEGORIES:
        tp = sum(r["categories"][category]["tp"] for r in results)
        fp = sum(len(r["categories"][category]["fp"]) for r in results)
        fn = sum(len(r["categories"][category]["fn"]) for r in results)
        totals[category] = {
            "tp": tp,
            "fp": fp,
            "fn": fn,
            "precision": _ratio(tp, tp + fp),
            "recall": _ratio(tp, tp + fn),
        }
    return totals


def markdown(results: list[dict[str, Any]], totals: dict[str, dict[str, Any]]) -> str:
    lines = [
        "# Agent-security extraction accuracy (public repositories)",
        "",
        "Generated by `python -m benchmark.agent_security.evaluate`. Static extraction",
        "only; verdicts are not scored (public repositories ship no identity manifests).",
        "Ground truth is hand-reviewed by the tool author — see",
        "`docs/benchmark-methodology.md` for the bias this implies.",
        "",
        "| Category | TP | FP | FN | Precision | Recall |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for category, row in totals.items():
        lines.append(
            f"| {category} | {row['tp']} | {row['fp']} | {row['fn']} | "
            f"{row['precision'] if row['precision'] is not None else 'n/a'} | "
            f"{row['recall'] if row['recall'] is not None else 'n/a'} |"
        )
    lines += ["", "## Cases", ""]
    for result in results:
        lines.append(f"### {result['id']} — `{result['repository']}` @ `{result['commit'][:12]}`")
        lines.append(f"root `{result['root']}`")
        lines.append("")
        for category, row in result["categories"].items():
            if not (row["tp"] or row["fp"] or row["fn"]):
                continue
            fp, fn = len(row["fp"]), len(row["fn"])
            lines.append(f"- **{category}**: TP {row['tp']}, FP {fp}, FN {fn}")
            for label, items in (("FP", row["fp"]), ("FN", row["fn"])):
                for item in items:
                    lines.append(f"  - {label} `{item}`")
        lines.append(f"- unknown reasons: {', '.join(result['unknown_reasons']) or 'none'}")
        lines.append("")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--checkouts", type=Path, default=HERE.parent / "checkouts")
    parser.add_argument("--cases", type=Path, default=HERE / "cases.json")
    parser.add_argument(
        "--out", type=Path, default=HERE.parent / "reports" / "agent-security-latest"
    )
    args = parser.parse_args()
    cases = json.loads(args.cases.read_text(encoding="utf-8"))["cases"]
    results = [score_case(case, args.checkouts) for case in cases]
    totals = summarize(results)
    payload = {"totals": totals, "cases": results}
    # Bytes, not write_text: on Windows text mode would turn "\n" into "\r\n".
    args.out.with_suffix(".json").write_bytes((json.dumps(payload, indent=2) + "\n").encode())
    args.out.with_suffix(".md").write_bytes(markdown(results, totals).encode("utf-8"))
    for category, row in totals.items():
        print(f"{category:18} P={row['precision']} R={row['recall']} "
              f"(tp={row['tp']} fp={row['fp']} fn={row['fn']})")


if __name__ == "__main__":
    main()
